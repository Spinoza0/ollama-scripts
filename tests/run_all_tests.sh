#!/bin/bash

# =============================================================================
# Запуск всех тестов для Ollama Scripts
# =============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Цвета
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

echo "╔═══════════════════════════════════════════════════════════╗"
echo "║         Запуск всех тестов Ollama Scripts                 ║"
echo "╚═══════════════════════════════════════════════════════════╝"
echo ""

# Счётчик
TOTAL_TESTS=0
PASSED_TESTS=0

# =============================================================================
# Тест 1: lib.sh
# =============================================================================
echo -e "${YELLOW}═══ Запуск тестов lib.sh ═══${NC}"
echo ""
if "$SCRIPT_DIR/test_lib.sh"; then
    ((PASSED_TESTS++))
else
    echo -e "${RED}⚠️  Тесты lib.sh не пройдены${NC}"
fi
echo ""
((TOTAL_TESTS++))

# =============================================================================
# Тест 2: scripts.sh
# =============================================================================
echo -e "${YELLOW}═══ Запуск тестов scripts.sh ═══${NC}"
echo ""
if "$SCRIPT_DIR/test_scripts.sh"; then
    ((PASSED_TESTS++))
else
    echo -e "${RED}⚠️  Тесты scripts.sh не пройдены${NC}"
fi
echo ""
((TOTAL_TESTS++))

# =============================================================================
# Тест 3: integration.sh
# =============================================================================
echo -e "${YELLOW}═══ Запуск интеграционных тестов ═══${NC}"
echo ""
if "$SCRIPT_DIR/test_integration.sh"; then
    ((PASSED_TESTS++))
else
    echo -e "${RED}⚠️  Интеграционные тесты не пройдены${NC}"
fi
echo ""
((TOTAL_TESTS++))

# =============================================================================
# Итоги
# =============================================================================
echo "╔═══════════════════════════════════════════════════════════╗"
echo "║                    ОБЩИЕ ИТОГИ                            ║"
echo "╚═══════════════════════════════════════════════════════════╝"
echo ""
echo -e "${GREEN}✅ Пройдено тестов: $PASSED_TESTS из $TOTAL_TESTS${NC}"
echo ""

if [ $PASSED_TESTS -eq $TOTAL_TESTS ]; then
    echo -e "${GREEN}🎉 Все тесты пройдены!${NC}"
    exit 0
else
    echo -e "${YELLOW}⚠️  Некоторые тесты не пройдены${NC}"
    exit 1
fi
