#!/bin/bash

# =============================================================================
# Библиотека функций для работы с Ollama
# Подключается в другие скрипты через: source lib.sh
# =============================================================================

# -----------------------------------------------------------------------------
# Проверка, запущен ли сервис Ollama
# Возвращает: 0 если запущен, 1 если не запущен
# -----------------------------------------------------------------------------
ollama_is_running() {
    local status
    status=$(brew services list 2>/dev/null | grep ollama | awk '{print $2}')
    if [ "$status" = "started" ] || [ "$status" = "error" ]; then
        return 0
    fi
    return 1
}

# -----------------------------------------------------------------------------
# Получить статус сервиса Ollama
# Возвращает: started, error, stopped, none
# -----------------------------------------------------------------------------
ollama_get_status() {
    local status
    status=$(brew services list 2>/dev/null | grep ollama | awk '{print $2}')
    echo "${status:-none}"
}

# -----------------------------------------------------------------------------
# Проверка установки Ollama
# Возвращает: 0 если установлен, 1 если не установлен
# -----------------------------------------------------------------------------
ollama_is_installed() {
    if command -v ollama &> /dev/null; then
        return 0
    fi
    return 1
}

# -----------------------------------------------------------------------------
# Получить версию Ollama
# Возвращает: строку с версией (например, "ollama version is 0.32.14")
# -----------------------------------------------------------------------------
ollama_get_version() {
    local v
    v=$(ollama --version 2>&1 | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -1)
    echo "ollama version is ${v:-unknown}"
}

# -----------------------------------------------------------------------------
# Запуск сервиса Ollama с ожиданием
# Аргументы: $1 - максимальное время ожидания в секундах (по умолчанию 10)
# Возвращает: 0 если запущен, 1 если не удалось запустить
# -----------------------------------------------------------------------------
ollama_start_and_wait() {
    local max_wait="${1:-10}"
    local i
    
    brew services start ollama
    
    for i in $(seq 1 $max_wait); do
        if ollama_is_running; then
            return 0
        fi
        sleep 1
    done
    
    return 1
}

# -----------------------------------------------------------------------------
# Остановка сервиса Ollama
# -----------------------------------------------------------------------------
ollama_stop() {
    brew services stop ollama 2>/dev/null || true
}

# -----------------------------------------------------------------------------
# Проверка, что модель загружена
# Аргументы: $1 - имя модели
# Возвращает: 0 если загружена, 1 если нет
# -----------------------------------------------------------------------------
ollama_model_exists() {
    local model="$1"
    if ollama list 2>/dev/null | grep -q "$model"; then
        return 0
    fi
    return 1
}

# -----------------------------------------------------------------------------
# Получить список активных моделей в памяти
# Возвращает: список имён моделей (по одной на строку)
# -----------------------------------------------------------------------------
ollama_get_running_models() {
    ollama ps 2>/dev/null | tail -n +2 | awk '{print $1}'
}

# -----------------------------------------------------------------------------
# Остановить модель (выгрузить из памяти)
# Аргументы: $1 - имя модели
# -----------------------------------------------------------------------------
ollama_unload_model() {
    local model="$1"
    ollama stop "$model" 2>/dev/null || true
}

# -----------------------------------------------------------------------------
# Получить список установленных моделей
# Возвращает: список моделей (по одной на строку)
# -----------------------------------------------------------------------------
ollama_list_models() {
    ollama list 2>/dev/null | tail -n +2
}

# -----------------------------------------------------------------------------
# Удалить все модели
# -----------------------------------------------------------------------------
ollama_rm_all_models() {
    local models
    models=$(ollama_list_models)
    if [ -n "$models" ]; then
        for model in $models; do
            ollama rm "$model" 2>/dev/null || true
        done
    fi
}

# -----------------------------------------------------------------------------
# Загрузить конфигурацию config.env
# Порядок поиска:
#   1. $OLLAMA_SCRIPTS_CONFIG (если задан)
#   2. config.env рядом со скриптом (локальная установка)
#   3. /opt/homebrew/etc/ollama-scripts/config.env (установка через brew)
# -----------------------------------------------------------------------------
load_config() {
    local path="${OLLAMA_SCRIPTS_CONFIG:-}"
    if [ -z "$path" ] || [ ! -f "$path" ]; then
        if [ -f "$SCRIPT_DIR/config.env" ]; then
            path="$SCRIPT_DIR/config.env"
        elif [ -f "/opt/homebrew/etc/ollama-scripts/config.env" ]; then
            path="/opt/homebrew/etc/ollama-scripts/config.env"
        fi
    fi

    if [ -n "$path" ] && [ -f "$path" ]; then
        # shellcheck disable=SC1090
        source "$path"
        return 0
    fi

    echo "❌ Не найден config.env" >&2
    return 1
}

# -----------------------------------------------------------------------------
# Имя команды для вызова скрипта в зависимости от способа установки
# Аргументы: $1 - имя скрипта без расширения (например, run-chat)
# Возвращает: ./run-chat.sh (клон репо) или ollama-run-chat (установка через brew)
# -----------------------------------------------------------------------------
cmd_name() {
    local prog
    prog=$(basename "${BASH_SOURCE[1]:-$0}")
    if [[ "$prog" == ollama-* ]]; then
        echo "ollama-${1}"
    else
        echo "./${1}.sh"
    fi
}

# -----------------------------------------------------------------------------
# Ширина рамки для вывода заголовков
# -----------------------------------------------------------------------------
BOX_WIDTH=59

# -----------------------------------------------------------------------------
# Применить keep-alive к сервису Ollama
# Используется штатный механизм Homebrew: ~/.homebrew/services/ollama.env
# Аргументы: $1 - длительность (например, 10m)
# Возвращает: 0 если изменено, 2 если уже совпадает, 1 при ошибке
# -----------------------------------------------------------------------------
ollama_apply_keep_alive() {
    local keep_alive="$1"
    local env_file="${HOMEBREW_USER_CONFIG_HOME:-$HOME/.homebrew}/services/ollama.env"

    if [ -z "$keep_alive" ]; then
        return 1
    fi

    local current=""
    if [ -f "$env_file" ]; then
        current=$(grep '^OLLAMA_KEEP_ALIVE=' "$env_file" 2>/dev/null | tail -1 | cut -d= -f2-)
    fi

    if [ "$current" = "$keep_alive" ]; then
        return 2
    fi

    mkdir -p "$(dirname "$env_file")"
    if [ -f "$env_file" ]; then
        grep -v '^OLLAMA_KEEP_ALIVE=' "$env_file" > "$env_file.tmp" 2>/dev/null || true
        mv "$env_file.tmp" "$env_file"
    else
        : > "$env_file"
    fi
    echo "OLLAMA_KEEP_ALIVE=$keep_alive" >> "$env_file"

    return 0
}

# -----------------------------------------------------------------------------
# Печать горизонтальной границы рамки
# Аргументы: $1 - углы: top (╔╗) или bottom (╚╝)
# -----------------------------------------------------------------------------
box_border() {
    local left right
    if [ "$1" = "bottom" ]; then
        left='╚'; right='╝'
    else
        left='╔'; right='╗'
    fi
    printf '%s' "$left"
    printf '═%.0s' $(seq 1 "$BOX_WIDTH")
    printf '%s\n' "$right"
}

# -----------------------------------------------------------------------------
# Печать строки внутри рамки (выравнивание по левому краю)
# Аргументы: $1 - текст строки
# -----------------------------------------------------------------------------
box_line() {
    local text="$1"
    local len pad
    len=$(printf '%s' "$text" | wc -m | tr -d ' ')
    pad=$((BOX_WIDTH - 2 - len))
    printf '║ %s%*s ║\n' "$text" "$pad" ""
}
