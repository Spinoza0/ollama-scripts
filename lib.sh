#!/bin/bash

# =============================================================================
# Библиотека функций для работы с Ollama
# Подключается в другие скрипты через: source lib.sh
# =============================================================================

# -----------------------------------------------------------------------------
# Проверка, запущен ли сервис Ollama
# Возвращает: 0 если запущен, 1 если не запущен
# -----------------------------------------------------------------------------
ollama_is_running() {
    local status
    status=$(brew services list 2>/dev/null | grep ollama | awk '{print $2}')
    if [ "$status" = "started" ] || [ "$status" = "error" ]; then
        return 0
    fi
    return 1
}

# -----------------------------------------------------------------------------
# Получить статус сервиса Ollama
# Возвращает: started, error, stopped, none
# -----------------------------------------------------------------------------
ollama_get_status() {
    local status
    status=$(brew services list 2>/dev/null | grep ollama | awk '{print $2}')
    echo "${status:-none}"
}

# -----------------------------------------------------------------------------
# Проверка установки Ollama
# Возвращает: 0 если установлен, 1 если не установлен
# -----------------------------------------------------------------------------
ollama_is_installed() {
    if command -v ollama &> /dev/null; then
        return 0
    fi
    return 1
}

# -----------------------------------------------------------------------------
# Получить версию Ollama
# Возвращает: строку с версией
# -----------------------------------------------------------------------------
ollama_get_version() {
    ollama --version 2>&1 | head -1
}

# -----------------------------------------------------------------------------
# Запуск сервиса Ollama с ожиданием
# Аргументы: $1 - максимальное время ожидания в секундах (по умолчанию 10)
# Возвращает: 0 если запущен, 1 если не удалось запустить
# -----------------------------------------------------------------------------
ollama_start_and_wait() {
    local max_wait="${1:-10}"
    local i
    
    brew services start ollama
    
    for i in $(seq 1 $max_wait); do
        if ollama_is_running; then
            return 0
        fi
        sleep 1
    done
    
    return 1
}

# -----------------------------------------------------------------------------
# Остановка сервиса Ollama
# -----------------------------------------------------------------------------
ollama_stop() {
    brew services stop ollama 2>/dev/null || true
}

# -----------------------------------------------------------------------------
# Проверка, что модель загружена
# Аргументы: $1 - имя модели
# Возвращает: 0 если загружена, 1 если нет
# -----------------------------------------------------------------------------
ollama_model_exists() {
    local model="$1"
    if ollama list 2>/dev/null | grep -q "$model"; then
        return 0
    fi
    return 1
}

# -----------------------------------------------------------------------------
# Получить список активных моделей в памяти
# Возвращает: список имён моделей (по одной на строку)
# -----------------------------------------------------------------------------
ollama_get_running_models() {
    ollama ps 2>/dev/null | tail -n +2 | awk '{print $1}'
}

# -----------------------------------------------------------------------------
# Остановить модель (выгрузить из памяти)
# Аргументы: $1 - имя модели
# -----------------------------------------------------------------------------
ollama_unload_model() {
    local model="$1"
    ollama stop "$model" 2>/dev/null || true
}

# -----------------------------------------------------------------------------
# Получить список установленных моделей
# Возвращает: список моделей (по одной на строку)
# -----------------------------------------------------------------------------
ollama_list_models() {
    ollama list 2>/dev/null | tail -n +2
}

# -----------------------------------------------------------------------------
# Удалить все модели
# -----------------------------------------------------------------------------
ollama_rm_all_models() {
    local models
    models=$(ollama_list_models)
    if [ -n "$models" ]; then
        for model in $models; do
            ollama rm "$model" 2>/dev/null || true
        done
    fi
}
